#!/usr/bin/env node
/**
 * Download the self-hosted web fonts and write the @font-face rules.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * Production sets body copy in Roboto and every heading, nav item and button in
 * "Vinila Extended" — a commercial Dinamo face that cannot be redistributed. Roboto is
 * Apache-2.0 and is taken as-is. For the display face, Archivo is used at its expanded
 * width: it is the closest free grotesque with the same wide, squarish proportions, and
 * it is a variable font, so one file per subset covers every weight and width the
 * rebuild uses. The substitution is recorded in docs/visual-comparison.md.
 *
 * Both families are asked for as variable fonts, so the whole set is six files. Only
 * the subsets the twelve locales need are kept: latin, latin-ext and cyrillic.
 *
 * Everything is fetched once and committed, so the build never touches the network.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { get as httpsGet } from 'node:https';

/**
 * The Google Fonts endpoints are dual-stack and this machine has no IPv6 route, so the
 * global fetch's connection attempts fail on the AAAA address. Pin the family instead.
 */
function get(url, headers = {}) {
  return new Promise((resolve, reject) => {
    httpsGet(url, { family: 4, headers: { 'user-agent': UA, ...headers } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        resolve(get(new URL(res.headers.location, url).toString(), headers));
        return;
      }
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error(`${res.statusCode} for ${url}`));
        return;
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

/** the Google Fonts CSS endpoint, asked for as a modern browser so it answers woff2 */
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { family: 'Roboto', query: 'Roboto:wdth,wght@75..100,100..900', slug: 'roboto' },
  { family: 'Archivo', query: 'Archivo:wdth,wght@100..125,400..800', slug: 'archivo' },
];

const WANTED_SUBSETS = new Set(['latin', 'latin-ext', 'cyrillic']);

const OUT_DIR = 'public/fonts';
mkdirSync(OUT_DIR, { recursive: true });

/** each @font-face block is preceded by a comment naming the subset */
function parse(css) {
  const blocks = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const body = m[2];
    const get = (prop) => body.match(new RegExp(prop + ':\\s*([^;]+);'))?.[1]?.trim() ?? '';
    const url = body.match(/url\(([^)]+)\)/)?.[1];
    if (!url) continue;
    blocks.push({
      subset: m[1],
      family: get('font-family').replace(/['"]/g, ''),
      weight: get('font-weight'),
      stretch: get('font-stretch'),
      style: get('font-style') || 'normal',
      range: get('unicode-range'),
      url,
    });
  }
  return blocks;
}

let css = `/*
 * Self-hosted web fonts. Generated by scripts/fetch-fonts.mjs — do not edit by hand.
 *
 * Roboto is Apache-2.0 and is what production sets body copy in. "Vinila Extended", the
 * face production uses for every heading, nav item and button, is a commercial Dinamo
 * typeface and cannot be redistributed, so Archivo stands in for it; the rebuild styles
 * it with an expanded font-stretch to match the proportions. See
 * docs/visual-comparison.md.
 */

`;

for (const { query, slug } of FAMILIES) {
  const res = await get(`https://fonts.googleapis.com/css2?family=${query}&display=swap`);
  const blocks = parse(res.toString('utf8')).filter((b) => WANTED_SUBSETS.has(b.subset));

  /** Google's variable-font answer repeats one file per weight; take it once per subset */
  const done = new Set();
  for (const b of blocks) {
    if (done.has(b.subset)) continue;
    done.add(b.subset);

    const bytes = await get(b.url);

    const name = `${slug}-${b.subset}-${createHash('sha256').update(bytes).digest('hex').slice(0, 8)}.woff2`;
    writeFileSync(`${OUT_DIR}/${name}`, bytes);
    console.log(`  ${name}  ${(bytes.length / 1024).toFixed(1)} kB`);

    css += `@font-face {\n  font-family: '${b.family}';\n  font-style: ${b.style};\n  font-weight: ${b.weight};\n`;
    if (b.stretch) css += `  font-stretch: ${b.stretch};\n`;
    css += `  font-display: swap;\n  src: url('/fonts/${name}') format('woff2');\n  unicode-range: ${b.range};\n}\n\n`;
  }
}

writeFileSync('src/styles/fonts.css', css, 'utf8');
console.log('\nwrote src/styles/fonts.css');
