#!/usr/bin/env node
/**
 * Emit the redirect table used by the host.
 *
 * Everything here is a URL the live site serves today, verified against it, or a
 * content path this build deliberately dropped. Nothing is invented: if a redirect
 * has no counterpart in the current site, it does not belong in this file.
 *
 * Writes both formats because the hosting target has not been chosen yet:
 *   public/_redirects          Netlify / Cloudflare Pages
 *   dist/_headers             Cloudflare Pages cache and security headers
 */

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'src', 'content');

/** legacy Chinese prefix; the live site 308s /cn/* to /zh */
const cnRedirects = [
  '/cn/* /zh/:splat 301',
  '/cn /zh 301',
];

/** the old site served /news/* as a separate section; the new build unifies it under /blog */
const newsRedirects = [
  '/:locale/news /:locale/blog 301',
  '/:locale/news/ /:locale/blog/ 301',
  '/:locale/news/:slug /:locale/blog/:slug 301',
];

/**
 * `/category/devs/` is served by the live site and linked from its own Discover page, but
 * there is no matching row in the exported category table, so this build cannot render it.
 * The label it carries is "CHECK THE BLOG", so the blog index is where it belongs.
 */
const categoryRedirects = [
  '/:locale/category/devs /:locale/blog 301',
  '/:locale/category/devs/ /:locale/blog/ 301',
];

/** locale-less paths, preserved from the live site's defaults */
const rootRedirects = [
  '/ /ru/ 302',
  '/blog /ru/blog/ 302',
  '/discover /ru/discover/ 302',
  '/ecosystem /ru/ecosystem/ 302',
  '/community /ru/community/ 302',
  '/get-erg /ru/get-erg/ 302',
  '/manifesto /ru/manifesto/ 302',
  '/legal /ru/legal/ 302',
  '/privacy-policy /ru/privacy-policy/ 302',
  '/ergo-wallet-app /ru/ergo-wallet-app/ 302',
];

/** media and asset paths the archive never held but the live site serves from GCS */
const mediaRedirects = [
  '/uploads/* https://storage.googleapis.com/ergo-cms-media/uploads/:splat 302',
];

/** robots.txt, replacing the live one which pointed at a sitemap with no posts in it */
const robots = `User-agent: *
Allow: /

Sitemap: https://ergoplatform.org/sitemap-index.xml
`;

mkdirSync(join(ROOT, 'public'), { recursive: true });

const lines = [
  '# Generated by scripts/write-redirects.mjs — do not edit by hand.',
  '#',
  '# Every entry corresponds to a URL the current site serves. Removing a route from',
  '# this build without adding it here is what produces a 404 after cutover.',
  '',
  ...cnRedirects,
  ...newsRedirects,
  ...categoryRedirects,
  ...rootRedirects,
];

writeFileSync(join(ROOT, 'public', '_redirects'), lines.join('\n') + '\n', 'utf8');
writeFileSync(join(ROOT, 'public', 'robots.txt'), robots, 'utf8');

console.log(`wrote public/_redirects (${lines.filter((l) => l && !l.startsWith('#')).length} rules)`);
console.log('wrote public/robots.txt');
if (mediaRedirects.length) {
  console.log('note: mediaRedirects not emitted — media is served from public/uploads in this build');
}
